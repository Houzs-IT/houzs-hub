-- What each outside service costs and which company card pays for it. Replaces the
-- Register, Overview and Cards tabs of the API card register sheet. Cards keep only
-- their last 4 digits; never a full number, expiry or security code.
CREATE TABLE cards (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  nickname TEXT NOT NULL UNIQUE,
  last4 TEXT NOT NULL DEFAULT '' CHECK (last4 ~ '^([0-9]{4})?$'),
  bank TEXT NOT NULL DEFAULT '',
  holder TEXT NOT NULL DEFAULT '',
  company TEXT NOT NULL DEFAULT '',
  statement_day INTEGER CHECK (statement_day BETWEEN 1 AND 31),
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE cards ENABLE ROW LEVEL SECURITY;

-- One row per bill line, like a Register row: an account can carry several (Cloudflare
-- hosting monthly plus a domain yearly). card is a cards.nickname, or 'No card'.
CREATE TABLE charges (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  register_id TEXT NOT NULL DEFAULT '',
  account_id INTEGER REFERENCES accounts(id) ON DELETE SET NULL,
  company TEXT NOT NULL DEFAULT '',
  system TEXT NOT NULL DEFAULT '',
  vendor TEXT NOT NULL,
  service_type TEXT NOT NULL DEFAULT '',
  used_for TEXT NOT NULL DEFAULT '',
  plan TEXT NOT NULL DEFAULT '',
  amount NUMERIC(12, 2),
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency IN ('USD', 'MYR')),
  billed TEXT NOT NULL DEFAULT '' CHECK (billed IN ('', 'monthly', 'yearly')),
  card TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'to_confirm' CHECK (status IN ('confirmed', 'to_confirm', 'to_fill_in', 'not_active', 'cancelled')),
  checked_on TEXT,
  key_name TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE charges ENABLE ROW LEVEL SECURITY;

