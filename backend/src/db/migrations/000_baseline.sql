-- 000: the whole database as of 2026-10-15, replacing migrations 001 to 019.
-- A database that already ran 019 records this file as applied without running it
-- (see scripts/migrate.mjs). New changes go in 020 and up.
-- Timestamps are ISO-8601 UTC strings written by the Worker; the SPA renders GMT+8.
-- Names starting "developers_" (constraints, the id counter) are kept from before the table was renamed
-- to users, so later migrations can name them the same way on every database.

-- The systems that can file tickets. API keys are issued by scripts/issue-api-key.mjs,
-- so no secret lives here.
CREATE TABLE systems (
  code TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  api_key_hash TEXT UNIQUE,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  -- For the Integrations page: last valid API call, and the last failed send
  -- (cleared by the next successful one).
  last_call_at TEXT,
  last_send_error TEXT,
  last_send_error_at TEXT
);

CREATE TABLE ticket_sequences (
  system_code TEXT PRIMARY KEY REFERENCES systems(code),
  next_n INTEGER NOT NULL DEFAULT 1
);

-- Permissions are comma-joined keys, see services/perms.ts.
CREATE TABLE roles (
  key TEXT PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  permissions TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);

-- Accounts are made by scripts/set-password.mjs or the Users page; a NULL password_hash
-- cannot sign in. The username is the sign-in name; email is optional.
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME developers_id_seq) CONSTRAINT developers_pkey PRIMARY KEY,
  email TEXT CONSTRAINT developers_email_key UNIQUE,
  name TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  last_seen_at TEXT,
  username TEXT CONSTRAINT developers_username_key UNIQUE,
  password_hash TEXT,
  failed_logins INTEGER NOT NULL DEFAULT 0,
  locked_until TEXT,
  role TEXT NOT NULL DEFAULT 'developer' CONSTRAINT users_role_fkey REFERENCES roles(key),
  -- A password an admin handed out works once: the next sign-in must choose a new one.
  must_change_password INTEGER NOT NULL DEFAULT 0,
  -- The portal page last open, for "Online now". Only trusted while last_seen_at is recent.
  viewing_page TEXT,
  -- Override the role for one user; deny wins.
  perm_allow TEXT NOT NULL DEFAULT '',
  perm_deny TEXT NOT NULL DEFAULT '',
  -- Notifications are ticket events; read up to this event id. NULL until the first visit.
  notifications_seen_id INTEGER
);

CREATE TABLE tickets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  legacy_code TEXT,
  system_code TEXT NOT NULL REFERENCES systems(code),
  type TEXT NOT NULL CHECK (type IN ('bug', 'development')),
  priority TEXT NOT NULL CHECK (priority IN ('urgent', 'high', 'medium', 'low')),
  status TEXT NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'in_progress', 'on_hold', 'testing', 'waiting_reporter', 'resolved', 'closed', 'rejected')),
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  occurred_at TEXT,
  reporter_external_id TEXT NOT NULL,
  reporter_name TEXT NOT NULL,
  reporter_email TEXT,
  reporter_phone TEXT,
  reporter_department TEXT,
  page_url TEXT,
  user_agent TEXT,
  app_version TEXT,
  assignee_id INTEGER REFERENCES users(id),
  picked_up_at TEXT,
  resolved_at TEXT,
  closed_at TEXT,
  -- Drives the unread badge in the reporting system: unread when a developer
  -- acted publicly after reporter_seen_at.
  last_public_activity_at TEXT NOT NULL,
  last_public_actor TEXT NOT NULL CHECK (last_public_actor IN ('reporter', 'developer', 'system')),
  reporter_seen_at TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  -- Hand-sorted order inside a Board column. NULL means not placed yet; those show on top.
  board_rank INTEGER
);
CREATE INDEX idx_tickets_status ON tickets(status, updated_at);
CREATE INDEX idx_tickets_reporter ON tickets(system_code, reporter_external_id, updated_at);
CREATE INDEX idx_tickets_assignee ON tickets(assignee_id, status);
CREATE INDEX idx_tickets_created ON tickets(created_at);
CREATE INDEX idx_tickets_updated ON tickets(updated_at);
CREATE INDEX idx_tickets_status_board_rank ON tickets(status, board_rank);

-- Deleting a ticket takes its events and attachment rows with it.
-- The attachment files in R2 are not removed; delete those separately.
CREATE TABLE ticket_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('created', 'comment', 'status', 'assign', 'priority', 'type')),
  visibility TEXT NOT NULL CHECK (visibility IN ('public', 'internal')),
  author_kind TEXT NOT NULL CHECK (author_kind IN ('reporter', 'developer', 'system')),
  author_name TEXT NOT NULL,
  user_id INTEGER CONSTRAINT ticket_events_developer_id_fkey REFERENCES users(id),
  body TEXT,
  from_value TEXT,
  to_value TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX idx_ticket_events_ticket ON ticket_events(ticket_id, id);
CREATE INDEX idx_ticket_events_kind ON ticket_events(kind, id);

-- Every attachment hangs off an event so an internal note's files inherit
-- its visibility and never reach the reporter.
CREATE TABLE ticket_attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  event_id INTEGER NOT NULL REFERENCES ticket_events(id) ON DELETE CASCADE,
  r2_key TEXT NOT NULL UNIQUE,
  filename TEXT NOT NULL,
  mime TEXT NOT NULL,
  size INTEGER NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX idx_ticket_attachments_ticket ON ticket_attachments(ticket_id);
CREATE INDEX idx_ticket_attachments_event ON ticket_attachments(event_id);

-- Supabase serves every table in `public` over its REST API to anyone holding
-- the project's anon key. Row level security with no policy shuts that door;
-- the Worker connects as the table owner, which RLS does not restrict.
