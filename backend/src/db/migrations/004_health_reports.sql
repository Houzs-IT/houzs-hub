-- Health reports a system sends the hub with its own hub API key (no person signs in):
-- the same live state its own health page shows. 7 days are kept; the page shows the latest.
CREATE TABLE health_reports (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  system_code TEXT NOT NULL REFERENCES systems(code) ON DELETE CASCADE,
  received_at TEXT NOT NULL,
  ok INTEGER NOT NULL,
  report JSONB NOT NULL
);
ALTER TABLE health_reports ENABLE ROW LEVEL SECURITY;
CREATE INDEX health_reports_system_time ON health_reports (system_code, received_at DESC);
