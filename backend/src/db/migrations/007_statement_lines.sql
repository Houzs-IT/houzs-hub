-- Charges as they appear on the company card statements, in ringgit. Replaces the
-- Statement lines tab of the API card register sheet; the Monthly and Trend views are
-- worked out from these on the Billing page. register_id ties a line to its charge.
CREATE TABLE statement_lines (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  txn_date TEXT NOT NULL CHECK (txn_date ~ '^\d{4}-\d{2}-\d{2}$'),
  card TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  register_id TEXT NOT NULL DEFAULT '',
  amount_myr NUMERIC(12, 2) NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE statement_lines ENABLE ROW LEVEL SECURITY;
CREATE INDEX statement_lines_txn_date ON statement_lines (txn_date);
