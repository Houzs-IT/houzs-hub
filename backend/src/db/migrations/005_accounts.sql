-- Outside accounts the companies depend on (Cloudflare, Supabase, GitHub, email
-- senders, AI, domains...) and who controls each, so every one can end up under
-- it@houzscentury.com. Replaces the Ownership tab of the API card register sheet.
-- Never holds passwords, API keys or card numbers: names, emails and roles only.
CREATE TABLE accounts (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  companies TEXT NOT NULL DEFAULT '',
  vendor TEXT NOT NULL DEFAULT '',
  main_owner TEXT NOT NULL DEFAULT '',
  control TEXT NOT NULL DEFAULT '',
  it_access TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'not_yet' CHECK (status IN ('yes', 'partly', 'not_yet', 'cant_move')),
  bills_to TEXT NOT NULL DEFAULT '',
  register_ids TEXT NOT NULL DEFAULT '',
  next_step TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;

-- Admin gets both new permissions; other roles get them on the Roles page.
UPDATE roles SET permissions = permissions || ',accounts_view,accounts_edit'
  WHERE key = 'admin' AND permissions NOT LIKE '%accounts_view%';
