-- Vendor invoices for System billing. An invoice is for one charge (the vendor account it
-- is billed to) and is paid by at most one card statement line. Its PDF is kept in R2.
CREATE TABLE invoices (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  vendor TEXT NOT NULL,
  invoice_no TEXT NOT NULL,
  invoice_date TEXT NOT NULL CHECK (invoice_date ~ '^\d{4}-\d{2}-\d{2}$'),
  period_from TEXT CHECK (period_from ~ '^\d{4}-\d{2}-\d{2}$'),
  period_to TEXT CHECK (period_to ~ '^\d{4}-\d{2}-\d{2}$'),
  bill_to TEXT NOT NULL DEFAULT '',
  total NUMERIC(12, 2) NOT NULL,
  currency TEXT NOT NULL DEFAULT 'USD' CHECK (currency IN ('USD', 'MYR')),
  charge_id INTEGER REFERENCES charges(id) ON DELETE SET NULL,
  statement_line_id INTEGER UNIQUE REFERENCES statement_lines(id) ON DELETE SET NULL,
  file_key TEXT,
  file_name TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT,
  UNIQUE (vendor, invoice_no)
);
ALTER TABLE invoices ENABLE ROW LEVEL SECURITY;

-- The lines that cost money. project_ref is the project the vendor printed (Supabase), if any.
CREATE TABLE invoice_lines (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  invoice_id INTEGER NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  description TEXT NOT NULL DEFAULT '',
  project_ref TEXT NOT NULL DEFAULT '',
  amount NUMERIC(12, 2) NOT NULL,
  kind TEXT NOT NULL DEFAULT 'charge' CHECK (kind IN ('charge', 'tax', 'discount', 'rounding'))
);
ALTER TABLE invoice_lines ENABLE ROW LEVEL SECURITY;
CREATE INDEX invoice_lines_invoice ON invoice_lines (invoice_id);

-- Project IDs vendors print on invoices, and what each one is. Learned the first time an
-- invoice shows one; a person names it and says whether it is still in use.
CREATE TABLE project_refs (
  ref TEXT PRIMARY KEY,
  vendor TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  charge_id INTEGER REFERENCES charges(id) ON DELETE SET NULL,
  in_use INTEGER NOT NULL DEFAULT 1 CHECK (in_use IN (0, 1)),
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE project_refs ENABLE ROW LEVEL SECURITY;

-- A statement line with no invoice to be had (e.g. a vendor that sends none) can be
-- checked by a person instead; the note says why.
ALTER TABLE statement_lines
  ADD COLUMN checked_by_hand INTEGER NOT NULL DEFAULT 0 CHECK (checked_by_hand IN (0, 1));
