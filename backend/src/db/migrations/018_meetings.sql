-- Meeting rooms shared by every company (owner, 2026-11-22). The hub keeps the rooms,
-- the meetings, who is in them and the guest booking links; each ERP shows them on its
-- own Meetings page and calls these tables only through /api/v1/sys/meetings.
--
-- A person is one key across systems: their email in lower case when the system has
-- one, else "<system code>:<user id>". The same person signed in to Houzs ERP and to
-- Hookka ERP is then one person with one calendar.

CREATE TABLE meeting_people (
  system_code TEXT NOT NULL REFERENCES systems(code),
  external_id TEXT NOT NULL,
  person_key TEXT NOT NULL,
  name TEXT NOT NULL,
  email TEXT,
  company TEXT NOT NULL DEFAULT '',
  department TEXT NOT NULL DEFAULT '',
  active BOOLEAN NOT NULL DEFAULT true,
  synced_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (system_code, external_id)
);
CREATE INDEX idx_meeting_people_key ON meeting_people(person_key);

CREATE TABLE meeting_rooms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT '',
  floor TEXT NOT NULL DEFAULT '',
  seats INTEGER NOT NULL CHECK (seats > 0),
  equipment TEXT[] NOT NULL DEFAULT '{}',
  open_days INTEGER[] NOT NULL DEFAULT '{1,2,3,4,5}',
  open_from INTEGER NOT NULL DEFAULT 9 CHECK (open_from BETWEEN 0 AND 23),
  open_to INTEGER NOT NULL DEFAULT 18 CHECK (open_to BETWEEN 1 AND 24),
  color TEXT NOT NULL DEFAULT '#0b8043',
  buffer_min INTEGER NOT NULL DEFAULT 0 CHECK (buffer_min BETWEEN 0 AND 120),
  max_hours INTEGER NOT NULL DEFAULT 0 CHECK (max_hours >= 0),
  advance_days INTEGER NOT NULL DEFAULT 0 CHECK (advance_days >= 0),
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_by TEXT
);

CREATE TABLE meeting_room_closures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER NOT NULL REFERENCES meeting_rooms(id) ON DELETE CASCADE,
  from_date DATE NOT NULL,
  to_date DATE NOT NULL CHECK (to_date >= from_date),
  reason TEXT NOT NULL DEFAULT ''
);

CREATE TABLE meeting_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  room_ids INTEGER[] NOT NULL,
  length_min INTEGER NOT NULL CHECK (length_min BETWEEN 15 AND 480),
  days INTEGER[] NOT NULL,
  from_hour INTEGER NOT NULL,
  to_hour INTEGER NOT NULL,
  until DATE,
  host_keys TEXT[] NOT NULL,
  created_in TEXT NOT NULL REFERENCES systems(code),
  active BOOLEAN NOT NULL DEFAULT true,
  created_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE meetings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL CHECK (ends_at > starts_at),
  room_id INTEGER REFERENCES meeting_rooms(id),
  organizer TEXT NOT NULL,
  booked_by TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  video_type TEXT NOT NULL DEFAULT 'none' CHECK (video_type IN ('none', 'meet', 'zoom', 'link')),
  video_url TEXT NOT NULL DEFAULT '',
  reminders JSONB NOT NULL DEFAULT '[{"min":15,"ch":["erp"]}]',
  -- scheduled until it starts (by the button or by the clock), ended at the end time or
  -- when the organiser presses End; cancelled rows stay for the history.
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'live', 'ended', 'cancelled')),
  started_at TIMESTAMPTZ,
  ended_at TIMESTAMPTZ,
  series_id TEXT,
  created_in TEXT NOT NULL REFERENCES systems(code),
  link_id INTEGER REFERENCES meeting_links(id),
  guest JSONB,
  guest_token TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_meetings_time ON meetings(starts_at, ends_at) WHERE status <> 'cancelled';
CREATE INDEX idx_meetings_room ON meetings(room_id, starts_at) WHERE status <> 'cancelled';
CREATE INDEX idx_meetings_series ON meetings(series_id) WHERE series_id IS NOT NULL;
CREATE UNIQUE INDEX idx_meetings_guest_token ON meetings(guest_token) WHERE guest_token IS NOT NULL;

CREATE TABLE meeting_attendees (
  meeting_id INTEGER NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  person_key TEXT NOT NULL,
  PRIMARY KEY (meeting_id, person_key)
);
CREATE INDEX idx_meeting_attendees_person ON meeting_attendees(person_key);

CREATE TABLE meeting_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_id INTEGER NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  r2_key TEXT NOT NULL,
  file_name TEXT NOT NULL,
  mime_type TEXT NOT NULL DEFAULT 'application/octet-stream',
  size_bytes INTEGER NOT NULL,
  uploaded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE meeting_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meeting_id INTEGER NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  who TEXT NOT NULL,
  text TEXT NOT NULL
);
CREATE INDEX idx_meeting_history_meeting ON meeting_history(meeting_id);

CREATE TABLE meeting_notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  person_key TEXT NOT NULL,
  meeting_id INTEGER REFERENCES meetings(id) ON DELETE SET NULL,
  text TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at TIMESTAMPTZ
);
CREATE INDEX idx_meeting_notifications_person ON meeting_notifications(person_key, created_at DESC);

-- Room and link changes, for the Change log page.
CREATE TABLE meeting_admin_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  who TEXT NOT NULL,
  text TEXT NOT NULL
);

