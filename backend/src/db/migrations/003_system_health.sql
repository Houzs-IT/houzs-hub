-- System health: the hub checks each system's public health address every 5 minutes
-- and keeps 7 days of results. Only public addresses; no system's login or key is
-- stored here. page_url links to that system's own (signed-in) health page.
CREATE TABLE health_targets (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  system_code TEXT REFERENCES systems(code) ON DELETE SET NULL,
  check_url TEXT NOT NULL CHECK (check_url ~ '^https://'),
  page_url TEXT NOT NULL DEFAULT '',
  sort INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  updated_by TEXT
);
ALTER TABLE health_targets ENABLE ROW LEVEL SECURITY;

CREATE TABLE health_checks (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  target_id INTEGER NOT NULL REFERENCES health_targets(id) ON DELETE CASCADE,
  checked_at TEXT NOT NULL,
  ok INTEGER NOT NULL,
  status INTEGER,
  ms INTEGER,
  version TEXT,
  error TEXT
);
ALTER TABLE health_checks ENABLE ROW LEVEL SECURITY;
CREATE INDEX health_checks_target_time ON health_checks (target_id, checked_at DESC);

