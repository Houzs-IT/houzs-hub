// A small .xlsx writer: sheets of plain cells with a handful of fixed styles, packed
// into an uncompressed zip. Enough for exports people open in Excel or Google Sheets,
// without pulling a spreadsheet library into the bundle.

export type Style = "title" | "note" | "head" | "bold" | "rm" | "usd" | "pct" | "num" | "rmBold" | "usdBold" | "pctBold" | "right" | "rightBold";
export type Cell = string | number | null | undefined | { v: string | number | null; s: Style };
export type Sheet = { name: string; rows: Cell[][]; widths?: number[] };

